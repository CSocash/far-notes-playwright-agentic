// Copies the website's pages from the repository root into mobile/www for Capacitor to bundle,
// and adds config.js, which switches api-client.js into app mode.
//
//   FAR_NOTES_API_URL=https://farnotes.example.com npm run build   (one server for both platforms)
//   npm run build                                                  (local dev server on port 3000)
//
// Keep FILES in sync with serveStatic in server.js when a frontend file is added.
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "../..");
const WWW = path.resolve(__dirname, "../www");
const FILES = [
  "index.html", "login.html", "create-account.html", "forgot-password.html", "reset-password.html",
  "styles.css", "aircraft-front-view.png",
  "api-client.js", "app-core.js", "app.js",
  "login.js", "create-account.js", "forgot-password.js", "reset-password.js"
];

// Without FAR_NOTES_API_URL, each simulator reaches the dev server on this Mac:
// the iOS Simulator shares the Mac's network, and the Android emulator sees the Mac as 10.0.2.2.
const apiBase = process.env.FAR_NOTES_API_URL
  ? process.env.FAR_NOTES_API_URL.replace(/\/+$/, "")
  : { ios: "http://127.0.0.1:3000", android: "http://10.0.2.2:3000", default: "http://127.0.0.1:3000" };

fs.rmSync(WWW, { recursive: true, force: true });
fs.mkdirSync(WWW, { recursive: true });

for (const file of FILES) {
  const source = path.join(ROOT, file);
  if (!fs.existsSync(source)) throw new Error(`Missing frontend file: ${file}`);
  if (!file.endsWith(".html")) {
    fs.copyFileSync(source, path.join(WWW, file));
    continue;
  }
  const html = fs.readFileSync(source, "utf8");
  const apiClientTag = '<script src="api-client.js" defer></script>';
  if (!html.includes(apiClientTag)) throw new Error(`${file} doesn't load api-client.js`);
  fs.writeFileSync(path.join(WWW, file), html.replace(apiClientTag, `<script src="config.js"></script>\n    ${apiClientTag}`));
}

fs.writeFileSync(
  path.join(WWW, "config.js"),
  `// Generated by mobile/scripts/build-www.js. Do not edit.\nwindow.FAR_NOTES_CONFIG = ${JSON.stringify({ apiBase }, null, 2)};\n`
);

console.log(`Built ${FILES.length + 1} files into ${path.relative(ROOT, WWW)}/ (API: ${JSON.stringify(apiBase)})`);
